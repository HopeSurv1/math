_TITLES = dict(UNITS)

SOURCE_BOOKS = {"7_1.pdf": "7上", "7_2.pdf": "7下", "8_1.pdf": "8上",
                "8_2.pdf": "8下", "9_1.pdf": "9上", "9_2.pdf": "9下"}

_UNIT_CODE = re.compile(r"([789七八九])\s*([上下])\s*(\d)(?:\s*[-–－]\s*(\d))?")
_CHINESE_GRADES = {"七": "7", "八": "8", "九": "9"}


def unit_title(unit_id: str) -> str:
    return _TITLES.get(unit_id, "")


def normalize_unit(text: str) -> str:
    text = (text or "").strip()
    if not text:
        return ""
    match = _UNIT_CODE.search(text)
    if match:
        grade = _CHINESE_GRADES.get(match.group(1), match.group(1))
        unit_id = f"{grade}{match.group(2)} {match.group(3)}" + (f"-{match.group(4)}" if match.group(4) else "")
        if unit_id in _TITLES:
            return unit_id
    for unit_id, title in UNITS:
        if title == text:
            return unit_id
    return ""


def units_prompt() -> str:
    return "\n".join(f"{unit_id} {title}" for unit_id, title in UNITS)
